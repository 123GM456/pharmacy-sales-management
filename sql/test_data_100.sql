-- -------------------------------------------------------------
-- 3. 销售记录表：新增 100 条销售记录
--    药品取最新入库的 100 条（每条药品各销售一次），操作员在启用员工中轮转
--    销售时间分布在 2026-07-01 ~ 2026-09 下旬，覆盖"今日/本周/本月"查询范围
-- -------------------------------------------------------------
INSERT INTO sale (medicine_id, operator_id, quantity, sale_price, total_amount, sale_time, remark)
SELECT
    m.id,
    u.id,
    -- 数量 1~10 循环
    1 + ((s.rn * 7) MOD 10),
    m.sale_price,
    -- 总金额 = 单价 × 数量，与新增销售的业务口径一致
    m.sale_price * (1 + ((s.rn * 7) MOD 10)),
    -- 销售时间按编号错开：起点 2026-07-01，天数 0~86、分钟 0~539 循环
    TIMESTAMP('2026-07-01 09:00:00') + INTERVAL ((s.rn * 137) MOD 87) DAY + INTERVAL ((s.rn * 53) MOD 540) MINUTE,
    -- 备注在三种支付方式与空值之间轮转
    ELT((s.rn MOD 4) + 1, '现金支付', '微信支付', '支付宝支付', NULL)
FROM (
    WITH RECURSIVE seq AS (SELECT 1 rn UNION ALL SELECT rn + 1 FROM seq WHERE rn < 100)
    SELECT rn FROM seq
) s
-- 最新入库的 100 条药品，mn = 1..100 与编号一一对应
JOIN (
    SELECT id, sale_price, ROW_NUMBER() OVER (ORDER BY id DESC) AS mn
    FROM medicine
    ORDER BY id DESC
    LIMIT 100
) m ON m.mn = s.rn
-- 启用状态的员工全部参与排班，按编号对员工总数取模轮转
JOIN (
    SELECT id, ROW_NUMBER() OVER (ORDER BY id) AS un
    FROM sys_user
    WHERE role = 0 AND status = 1
) u ON u.un = ((s.rn - 1) MOD (SELECT COUNT(*) FROM sys_user WHERE role = 0 AND status = 1)) + 1;
